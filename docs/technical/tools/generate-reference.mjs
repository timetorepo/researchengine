#!/usr/bin/env node
/**
 * Generates the reference pages in docs/technical/reference/ from the source.
 *
 *   node docs/technical/tools/generate-reference.mjs
 *
 * Nothing here is hand-written: the API table comes from the `app.route(...)`
 * mounts in backend/src/index.ts and the `.get/.post/...` calls in each route
 * file; the component and module tables come from the exports and the header
 * comment of every file. Re-run it after adding routes or components.
 *
 * Zero dependencies, so it runs anywhere Node 20+ runs.
 */
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, relative, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(here, '..', '..', '..')
const OUT = join(ROOT, 'docs', 'technical', 'reference')
mkdirSync(OUT, { recursive: true })

const rel = (p) => relative(ROOT, p).split('\\').join('/')

function walk(dir, pred, acc = []) {
  for (const name of readdirSync(dir)) {
    if (['node_modules', 'dist', '.git', 'build'].includes(name)) continue
    const p = join(dir, name)
    if (statSync(p).isDirectory()) walk(p, pred, acc)
    else if (pred(p)) acc.push(p)
  }
  return acc
}

/** First meaningful lines of a file's leading comment, flattened to one line. */
function headerOf(file, max = 220) {
  const lines = readFileSync(file, 'utf8').split('\n').slice(0, 40)
  const out = []
  for (const raw of lines) {
    const s = raw.trim()
    if (/^(\/\/|\*|\/\*\*|\/\*)/.test(s)) {
      const t = s.replace(/^\/\*\*?|^\/\/|^\*\/?|\*\/$/g, '').trim()
      if (t) out.push(t)
    } else if (out.length) break
  }
  const text = out.join(' ').replace(/\s+/g, ' ').replace(/\|/g, '/').trim()
  // Slice by code point, so an emoji is never split in half.
  const chars = Array.from(text)
  return chars.length > max ? chars.slice(0, max - 1).join('').trimEnd() + '…' : text
}

const header = (title, note) => `# ${title}\n\n> Generated by \`docs/technical/tools/generate-reference.mjs\`. Do not edit by hand.\n${note ? `> ${note}\n` : ''}\n`

/* ------------------------------------------------------------------ */
/* 1. HTTP API                                                         */
/* ------------------------------------------------------------------ */

function apiReference() {
  const indexSrc = readFileSync(join(ROOT, 'backend/src/index.ts'), 'utf8')

  // Which file each route variable comes from (static and dynamic imports).
  const varToFile = new Map()
  for (const m of indexSrc.matchAll(/import \{ (\w+) \} from '\.\/(routes\/[\w-]+)'/g)) varToFile.set(m[1], m[2])
  for (const m of indexSrc.matchAll(/const \{ (\w+) \} = await import\('\.\/(routes\/[\w-]+)'\)/g)) varToFile.set(m[1], m[2])

  // Mounts: app.route('<prefix>', <var>) and app.route('<prefix>', <fn>(...)).
  const mounts = []
  for (const m of indexSrc.matchAll(/app\.route\('([^']+)',\s*(\w+)(?:\([^)]*\))?\)/g)) {
    const file = varToFile.get(m[2])
    if (file) mounts.push({ prefix: m[1], file: file + '.ts' })
  }

  // Routes declared inline in index.ts (the health check, the JSON guarantee).
  const rows = []
  const seen = new Set()
  const fileEndpoints = new Map()
  const endpointsIn = (file) => {
    if (fileEndpoints.has(file)) return fileEndpoints.get(file)
    const src = readFileSync(join(ROOT, 'backend/src', file), 'utf8')
    const hits = []
    for (const m of src.matchAll(/\b(\w+)\.(get|post|put|patch|delete|all)\(\s*'([^']*)'/g)) {
      hits.push({ method: m[2].toUpperCase(), path: m[3] })
    }
    fileEndpoints.set(file, hits)
    return hits
  }

  for (const mt of mounts) {
    for (const ep of endpointsIn(mt.file)) {
      const full = (mt.prefix + (ep.path === '/' ? '' : ep.path)) || '/'
      const key = `${ep.method} ${full}`
      if (seen.has(key)) continue
      seen.add(key)
      rows.push({ method: ep.method, path: full, file: mt.file.replace(/\.ts$/, '.ts') })
    }
  }
  rows.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method))

  const byFile = new Map()
  for (const r of rows) {
    const key = r.file
    if (!byFile.has(key)) byFile.set(key, [])
    byFile.get(key).push(r)
  }

  let md = header('HTTP API reference', 'Every route the single-process server mounts under /api. Paths are the full paths the browser calls.')
  md += `Total mounted endpoints found: **${rows.length}** across **${byFile.size}** route modules.\n\n`
  md += `Routes are mounted in \`backend/src/index.ts\`. Route modules live in \`backend/src/routes/\`.\n`
  md += `Some modules declare paths that are relative to their mount point, which is why the mount prefix is shown in the first column.\n\n`
  md += `| Method | Path | Module |\n|---|---|---|\n`
  for (const r of rows) md += `| \`${r.method}\` | \`${r.path}\` | \`backend/src/${r.file}\` |\n`
  md += `\n## Mount table\n\n| Prefix | Module |\n|---|---|\n`
  for (const m of mounts.sort((a, b) => a.prefix.localeCompare(b.prefix))) md += `| \`${m.prefix}\` | \`backend/src/${m.file}\` |\n`
  md += `\n## Not in this table\n\n`
  md += `- Handlers written inline in \`backend/src/index.ts\` (the JSON 404 catch-all and the static SPA handler) are not listed. Any \`/api/*\` path with no route answers JSON 404 with \`code: no_such_route\`.\n`
  md += `- The table is parsed from source text. Routes registered in a loop, or with a path built at runtime, will not appear.\n`
  writeFileSync(join(OUT, 'api-routes.md'), md)
  return rows.length
}

/* ------------------------------------------------------------------ */
/* 2. Frontend components                                              */
/* ------------------------------------------------------------------ */

function componentReference() {
  const base = join(ROOT, 'frontend/src/components')
  const files = walk(base, (p) => p.endsWith('.tsx')).sort()
  const groups = new Map()
  for (const f of files) {
    const src = readFileSync(f, 'utf8')
    const exps = [...src.matchAll(/^export (?:default )?(?:function|const|class) ([A-Z]\w*)/gm)].map((m) => m[1])
    const dir = rel(dirname(f)).replace('frontend/src/components', '').replace(/^\//, '') || '(root)'
    if (!groups.has(dir)) groups.set(dir, [])
    groups.get(dir).push({ file: rel(f), name: rel(f).split('/').pop(), exports: [...new Set(exps)], doc: headerOf(f, 160) })
  }
  const total = files.length
  let md = header('Frontend component reference', 'Every .tsx file under frontend/src/components, grouped by folder, with its exported components.')
  md += `**${total}** component files in **${groups.size}** folders.\n\n`
  md += `Folder names are relative to \`frontend/src/components/\`. The third-party folders (\`ui/*\`, \`smoothui/\`, \`shadcn-space/\`, \`spaceui/\`) hold vendored components; see \`THIRD-PARTY-NOTICES.md\` and the About tab for licences.\n\n`
  md += `## Folder index\n\n| Folder | Files |\n|---|---|\n`
  for (const [dir, list] of [...groups].sort((a, b) => a[0].localeCompare(b[0]))) md += `| \`${dir}\` | ${list.length} |\n`
  for (const [dir, list] of [...groups].sort((a, b) => a[0].localeCompare(b[0]))) {
    md += `\n## \`${dir}\`\n\n| File | Exports | Notes (from the file header) |\n|---|---|---|\n`
    for (const e of list) {
      const ex = e.exports.length ? e.exports.map((x) => `\`${x}\``).join(', ') : '—'
      md += `| \`${e.name}\` | ${ex} | ${e.doc || '—'} |\n`
    }
  }
  writeFileSync(join(OUT, 'components.md'), md)
  return total
}

/* ------------------------------------------------------------------ */
/* 3. Library modules (frontend/src/lib, backend/src/services, routes) */
/* ------------------------------------------------------------------ */

function moduleReference() {
  const sections = [
    ['Frontend lib', join(ROOT, 'frontend/src/lib'), (p) => /\.(ts|tsx)$/.test(p) && !/\.test\./.test(p)],
    ['Frontend stores and hooks', join(ROOT, 'frontend/src'), (p) => /\/(stores|hooks)\/[^/]+\.ts$/.test(p)],
    ['Backend services', join(ROOT, 'backend/src/services'), (p) => /\.ts$/.test(p)],
    ['Backend update and preview', join(ROOT, 'backend/src'), (p) => /\/(update|preview|db)\/[^/]+\.ts$/.test(p)],
  ]
  let count = 0
  let md = header('Module reference', 'Every non-component module, with the purpose stated in its header comment. Use it to find where something lives.')
  for (const [title, dir, pred] of sections) {
    const files = walk(dir, pred).sort()
    count += files.length
    md += `\n## ${title}\n\n| Module | Lines | Purpose (from the header comment) |\n|---|---|---|\n`
    for (const f of files) {
      const lines = readFileSync(f, 'utf8').split('\n').length
      md += `| \`${rel(f)}\` | ${lines} | ${headerOf(f) || '—'} |\n`
    }
  }
  writeFileSync(join(OUT, 'modules.md'), md)
  return count
}

/* ------------------------------------------------------------------ */
/* 4. npm scripts                                                      */
/* ------------------------------------------------------------------ */

function scriptsReference() {
  const pkgs = [
    ['root', 'package.json'],
    ['frontend', 'frontend/package.json'],
    ['backend', 'backend/package.json'],
    ['desktop', 'desktop/package.json'],
    ['website', 'website/package.json'],
  ]
  let md = header('npm scripts', 'Every script declared in the workspace package.json files.')
  let n = 0
  for (const [name, path] of pkgs) {
    let json
    try { json = JSON.parse(readFileSync(join(ROOT, path), 'utf8')) } catch { continue }
    const scripts = Object.entries(json.scripts ?? {})
    n += scripts.length
    md += `\n## ${name} (\`${path}\`)\n\n| Script | Command |\n|---|---|\n`
    for (const [k, v] of scripts) md += `| \`${k}\` | \`${String(v).replace(/\|/g, '\\|')}\` |\n`
  }
  writeFileSync(join(OUT, 'scripts.md'), md)
  return n
}

const endpoints = apiReference()
const components = componentReference()
const modules = moduleReference()
const scripts = scriptsReference()
console.log(`reference written to ${rel(OUT)}: ${endpoints} endpoints, ${components} components, ${modules} modules, ${scripts} scripts`)
