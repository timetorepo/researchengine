// Generates src/styles/heroui-v3.generated.css from the HeroUI v3 stylesheet
// (@heroui/styles, hoisted in the repo's node_modules).
//
// Why it exists: HeroUI v3 components (Accordion, ButtonGroup, Button, Tabs,
// Switch, InputOTP …) render slot classes from @heroui/styles, and those
// classes @apply Tailwind colour utilities such as `bg-accent` or `text-muted`.
// This app already owns those names with different meanings (its `muted` is
// an elevated surface, used ~100 times). So every HeroUI colour name is
// renamed into a `hui-` namespace (`bg-accent` -> `bg-hui-accent`), and the
// namespace is mapped onto the app's palette in globals.css.
//
// Run: node scripts/heroui-v3-css.mjs   (also wired into `prebuild`/`predev`).
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../src/styles/heroui-v3.generated.css');
const require = createRequire(import.meta.url);
const stylesDir = join(dirname(require.resolve('@heroui/styles/package.json')), 'dist');

const stripComments = (s) => s.replace(/\/\*[\s\S]*?\*\//g, '');

/** Inline `@import "./x.css";` recursively (relative paths only). */
function inline(file) {
  const dir = dirname(file);
  return stripComments(readFileSync(file, 'utf8')).replace(
    /@import\s+"(\.\/[^"]+)";/g,
    (_, rel) => inline(join(dir, rel)),
  );
}

const variables = stripComments(readFileSync(join(stylesDir, 'themes/default/variables.css'), 'utf8'));
const components = inline(join(stylesDir, 'components/index.css'));
const themeComponents = existsSync(join(stylesDir, 'themes/default/components/index.css'))
  ? inline(join(stylesDir, 'themes/default/components/index.css'))
  : '';
const utilities = stripComments(readFileSync(join(stylesDir, 'utilities/index.css'), 'utf8'));

// Colour tokens: every `--color-X: var(--Y);` in the shared theme.
const themeSrc = stripComments(readFileSync(join(stylesDir, 'themes/shared/theme.css'), 'utf8'));
const colours = [...themeSrc.matchAll(/--color-([a-z0-9-]+):\s*([^;]+);/g)].map((m) => ({ name: m[1], value: m[2].trim() }));
const names = colours.map((c) => c.name).sort((a, b) => b.length - a.length);
const nameRe = names.map((n) => n.replace(/[-]/g, '\\-')).join('|');

// Utility prefixes that take a colour (`bg-`, `text-`, `border-b-`, `ring-offset-` …).
const prefix = '(?:bg|text|ring|ring-offset|outline|from|to|via|shadow|decoration|stroke|fill|divide|placeholder|caret|accent|inset-ring|border(?:-[a-z]{1,2})?)';
const renameRe = new RegExp(`(?<![\\w-])(${prefix}-)(${nameRe})(?![\\w-])`, 'g');
const rename = (css) => css.replace(renameRe, (_, p, n) => `${p}hui-${n}`);

// The whole shared theme (radii, easing, animations, shadows and colours);
// only its colour declarations are renamed into the hui- namespace.
const themeBlock = rename(themeSrc.replace(/--color-([a-z0-9-]+):/g, (_, n) => `--color-hui-${n}:`));

const body = [
  '/* GENERATED by frontend/scripts/heroui-v3-css.mjs — do not edit. */',
  '/* HeroUI v3 styles (@heroui/styles), colour utilities renamed to hui-*. */',
  `@layer theme {\n${variables}\n}`,
  themeBlock,
  `@layer components {\n${rename(components)}\n${rename(themeComponents)}\n}`,
  rename(utilities),
  '',
].join('\n');

writeFileSync(out, body);
console.log(`heroui-v3.generated.css: ${(body.length / 1024).toFixed(0)} KB, ${colours.length} colour tokens`);
