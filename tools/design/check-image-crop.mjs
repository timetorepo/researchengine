import assert from 'node:assert/strict'
import { chromium } from './node_modules/playwright-core/index.mjs'
const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE, headless: true, chromiumSandbox: true })
try {
 const page = await browser.newPage({ viewport: { width: 1000, height: 900 } })
 const errors = []; page.on('pageerror', e => errors.push(e.message))
 await page.goto('http://127.0.0.1:5173/#/chats')
 await page.evaluate(async () => {
  const { useStore } = await import('/src/stores/useStore.ts')
  useStore.setState({ settings: { ...useStore.getState().settings, onboarded: true, reduceMotion: true } })
 })
 await page.reload()
 const skip = page.getByRole('button', { name: 'Skip', exact: true }); if (await skip.isVisible()) await skip.click()
 await page.getByRole('button', { name: 'Settings', exact: true }).click()
 await page.getByRole('dialog', { name: 'Settings', exact: true }).getByRole('button', { name: 'Profile', exact: true }).click()
 const png = await page.evaluate(() => { const c = document.createElement('canvas'); c.width = 800; c.height = 400; const ctx = c.getContext('2d'); ctx.fillStyle = '#ff3355'; ctx.fillRect(0, 0, 400, 400); ctx.fillStyle = '#3355ff'; ctx.fillRect(400, 0, 400, 400); return c.toDataURL().split(',')[1] })
 const upload = page.getByLabel('Upload profile photo', { exact: true })
 await upload.setInputFiles({ name: 'photo.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') })
 const crop = page.getByRole('dialog', { name: 'Crop profile photo', exact: true })
 await crop.waitFor()
 await crop.getByRole('button', { name: 'Apply crop', exact: true }).waitFor()
 await page.waitForFunction(() => !Array.from(document.querySelectorAll('button')).find(b => b.textContent === 'Apply crop')?.disabled)
 await page.screenshot({ path: '.cache/image-crop-desktop.png' })
 await crop.getByRole('button', { name: 'Rotate left' }).click()
 await crop.getByRole('button', { name: 'Flip horizontally' }).click()
 await crop.getByRole('button', { name: 'Reset', exact: true }).click()
 await crop.getByRole('button', { name: 'Apply crop', exact: true }).click()
 await crop.waitFor({ state: 'hidden' })
 await page.getByRole('button', { name: 'Remove photo', exact: true }).waitFor()
 const photo = await page.getByRole('dialog', { name: 'Settings', exact: true }).getByRole('img', { name: /profile photo/ }).first().evaluate(async img => { await img.decode(); return { width: img.naturalWidth, height: img.naturalHeight } })
 assert.equal(photo.width, photo.height); assert.ok(photo.width <= 512)

 await page.reload(); await page.getByRole('button', { name: 'Settings', exact: true }).click()
 await page.getByRole('dialog', { name: 'Settings', exact: true }).getByRole('button', { name: 'Profile', exact: true }).click()
 await page.getByRole('button', { name: 'Remove photo', exact: true }).waitFor()
 await page.getByLabel('Upload profile photo', { exact: true }).setInputFiles({ name: 'photo.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') })
 await crop.waitFor(); await page.keyboard.press('Escape'); await crop.waitFor({ state: 'hidden' })
 assert.equal(await page.getByRole('dialog', { name: 'Settings', exact: true }).count(), 1)
 await page.getByRole('button', { name: 'Remove photo', exact: true }).click()
 const state = await page.evaluate(async () => { const url = performance.getEntriesByType('resource').map(e => e.name).findLast(n => /\/src\/stores\/useStore\.ts(?:\?|$)/.test(n)); return (await import(url ?? '/src/stores/useStore.ts')).useStore.getState().settings.profile.avatar })
 assert.equal(state.kind, 'blobatar'); assert.ok(!state.photo)
 // Shared non-avatar API: original is byte-preserving, Cancel is null, invalid decode is recoverable.
 await page.evaluate(() => { window.cropPromise = import('/src/lib/images/crop.ts').then(async ({ cropImage }) => { const c = document.createElement('canvas'); c.width = 30; c.height = 20; const blob = await new Promise(r => c.toBlob(r)); const f = new File([blob], 'original.png', { type: 'image/png' }); const result = await cropImage(f); return result === f }) })
 const editor = page.getByRole('dialog', { name: 'Edit image', exact: true }); await editor.waitFor()
 await editor.getByRole('button', { name: 'Use original', exact: true }).click()
 assert.equal(await page.evaluate(() => window.cropPromise), true)
 await page.setViewportSize({ width: 390, height: 844 })
 await page.evaluate(() => { window.cropPromise = import('/src/lib/images/crop.ts').then(({ cropImage }) => cropImage(new File(['bad'], 'broken.png', { type: 'image/png' }))) })
 await editor.waitFor(); await editor.getByRole('alert').waitFor()
 await page.screenshot({ path: '.cache/image-crop-narrow.png' })
 await editor.getByRole('button', { name: 'Cancel', exact: true }).click()
 assert.equal(await page.evaluate(() => window.cropPromise), null)
 assert.deepEqual(errors, [])
 console.log('PASS: actual profile crop/export dimensions, persistence, nested Escape cancellation, photo removal, byte-preserving original, invalid-image recovery, narrow layout; no page errors')
} finally { await browser.close() }
