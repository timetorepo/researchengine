import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium } from './node_modules/playwright-core/index.mjs'
const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || undefined, headless: true, chromiumSandbox: true })
const base = process.env.SHELL_PREVIEW_URL ?? 'http://127.0.0.1:5173'
await mkdir('.cache/workspace-review', { recursive: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.goto(`${base}/#/settings`)
  await page.evaluate(async () => {
    const { useStore } = await import('/src/stores/useStore.ts')
    const { useUI } = await import('/src/stores/useUI.ts')
    const now = Date.now()
    useStore.setState({ chats: [
      { id: 'pinned-review', title: 'Pinned literature review', pinned: true, kind: 'research', updatedAt: now, createdAt: now, messages: [], settings: {} },
      { id: 'recent-build', title: 'Recent coding discussion', kind: 'coding', updatedAt: now - 1000, createdAt: now, messages: [], settings: {} },
    ], settings: { ...useStore.getState().settings, onboarded: true, workspaceLayout: 'focused', compact: true, reduceMotion: true, updates: { autoCheck: false } } })
    useUI.setState({ settingsTab: 'appearance', sidebarCollapsed: false })
  })
  const skip = page.getByRole('button', { name: 'Skip', exact: true })
  if (await skip.isVisible()) await skip.click()
  const workspace = page.getByRole('region', { name: 'Workspace layout', exact: true })
  await workspace.waitFor()
  await workspace.getByRole('button', { name: /^Overview/ }).click()
  await workspace.getByText('Learn', { exact: true }).click()
  const nav = page.getByRole('navigation', { name: 'Workspace', exact: true })
  assert.equal(await nav.getByRole('link', { name: 'Learn', exact: true }).count(), 1)
  const resizer = page.getByRole('separator', { name: 'Sidebar width' })
  await resizer.focus()
  await page.keyboard.press('End')
  assert.equal(await resizer.getAttribute('aria-valuenow'), '360')
  await page.keyboard.press('ArrowLeft')
  assert.equal(await resizer.getAttribute('aria-valuenow'), '352')
  const edge = await resizer.boundingBox()
  await page.mouse.move(edge.x + edge.width / 2, edge.y + 200)
  await page.mouse.down()
  await page.mouse.move(edge.x - 48, edge.y + 200)
  await page.mouse.up()
  assert.ok(Number(await resizer.getAttribute('aria-valuenow')) < 352)
  const width = await resizer.getAttribute('aria-valuenow')
  await page.waitForTimeout(600)
  await page.reload()
  await resizer.waitFor()
  assert.equal(await resizer.getAttribute('aria-valuenow'), width)
  assert.equal(await nav.getByRole('link', { name: 'Learn', exact: true }).count(), 1, 'Pinned tool survives reload')
  await page.goto(`${base}/#/`)
  await page.getByRole('region', { name: 'Your work', exact: true }).waitFor()
  await page.getByRole('region', { name: 'Your work', exact: true }).getByRole('button', { name: /Pinned literature review/ }).waitFor()
  await page.waitForTimeout(600)
  await page.screenshot({ path: '.cache/workspace-review/home-overview.png' })
  await page.goto(`${base}/#/chats`)
  await page.getByRole('heading', { name: 'Pinned', exact: true }).waitFor()
  await page.getByRole('heading', { name: 'Recent', exact: true }).waitFor()
  await page.getByRole('tab', { name: 'Coding 1', exact: true }).click()
  assert.equal(await page.getByRole('heading', { name: 'Pinned', exact: true }).count(), 0)
  await page.getByRole('tab', { name: 'All 2', exact: true }).click()
  const compactHeight = await page.locator('.re-history-list-row').first().evaluate((el) => el.getBoundingClientRect().height)
  await page.evaluate(async () => {
    const { useStore } = await import('/src/stores/useStore.ts')
    useStore.setState({ settings: { ...useStore.getState().settings, compact: false } })
  })
  await page.waitForTimeout(100)
  const comfortableHeight = await page.locator('.re-history-list-row').first().evaluate((el) => el.getBoundingClientRect().height)
  assert.ok(comfortableHeight > compactHeight, 'Density changes rendered row spacing')
  await page.getByRole('button', { name: 'Table', exact: true }).click()
  await page.getByRole('heading', { name: 'Coding', exact: true }).waitFor()
  await page.getByRole('button', { name: 'List', exact: true }).click()
  await page.getByRole('heading', { name: 'Pinned', exact: true }).waitFor()
  await page.waitForTimeout(400) // outgoing table rows finish their existing exit
  await page.getByRole('button', { name: 'Actions for Recent coding discussion', exact: true }).click()
  const renameAction = page.getByRole('menuitem', { name: 'Rename', exact: true })
  await renameAction.click()
  await page.getByRole('textbox', { name: 'Rename chat' }).fill('Renamed coding discussion')
  await page.keyboard.press('Enter')
  await page.getByRole('button', { name: 'Actions for Renamed coding discussion', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Rename', exact: true }).click()
  await page.getByRole('textbox', { name: 'Rename chat' }).fill('Do not save')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Actions for Renamed coding discussion', exact: true }).waitFor()
  await page.waitForTimeout(300)
  await page.screenshot({ path: '.cache/workspace-review/chats-list.png' })
  await page.evaluate(async () => {
    const { useStore } = await import('/src/stores/useStore.ts')
    useStore.setState({ settings: { ...useStore.getState().settings, workspaceLayout: 'studio', experimentalTabBar: true, glassMode: 'blur', navigationGlassStrength: 80 } })
  })
  await page.getByRole('complementary', { name: 'Workspace panel' }).waitFor()
  const glass = page.getByTestId('floating-navigation').locator('.lg-tab-bar-glass')
  await glass.waitFor()
  assert.match(await glass.evaluate((el) => getComputedStyle(el).backdropFilter), /blur\(24px\)/)
  await page.evaluate(async () => {
    const { useStore } = await import('/src/stores/useStore.ts')
    useStore.setState({ settings: { ...useStore.getState().settings, glassMode: 'off' } })
  })
  await page.waitForTimeout(100)
  assert.equal(await glass.evaluate((el) => getComputedStyle(el).backdropFilter), 'none')
  assert.equal(await page.getByTestId('floating-navigation').locator('.lg-tab-lens').evaluate((el) => getComputedStyle(el).backgroundColor), 'rgba(0, 0, 0, 0)', 'Solid material cannot cover selected labels')
  await page.waitForTimeout(200)
  await page.screenshot({ path: '.cache/workspace-review/chats-studio.png' })
  await page.getByRole('button', { name: /Pinned literature review/ }).first().click()
  await page.waitForURL('**/#/chat/pinned-review')
  assert.equal(await page.getByRole('complementary', { name: 'Workspace panel' }).count(), 0)
  await page.goto(`${base}/#/chats`)
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    await page.waitForTimeout(200)
    assert.equal(await page.getByRole('complementary', { name: 'Workspace panel' }).isVisible(), false)
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No page overflow')
    await page.screenshot({ path: `.cache/workspace-review/chats-${width}.png` })
  }
  await page.evaluate(async () => (await import('/src/stores/useStore.ts')).useStore.setState({ chats: [] }))
  await page.getByText('No conversations yet.', { exact: true }).waitFor()
  await page.goto(`${base}/#/`)
  await page.getByText('Your conversations will appear here once you start. Ask a question to begin.', { exact: true }).waitFor({ state: 'attached' })
  assert.deepEqual(errors, [])
  console.log('PASS: preset and pin persistence, drag/keyboard resizing, populated Home and list/table, Studio route/narrow policy, material effect, no page errors')
} finally { await browser.close() }
