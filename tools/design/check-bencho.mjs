// Real route integration checks in an isolated profile. External services are mocked explicitly.
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium } from './node_modules/playwright-core/index.mjs'
const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || undefined, chromiumSandbox: true, headless: true })
const base = process.env.SHELL_PREVIEW_URL ?? 'http://127.0.0.1:5173'
await mkdir('.cache/bencho-review-results', { recursive: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true })
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto(`${base}/#/settings`)
  await page.evaluate(async () => {
    const { useStore } = await import('/src/stores/useStore.ts')
    const { useUI } = await import('/src/stores/useUI.ts')
    const { useBots } = await import('/src/lib/bots/store.ts')
    useStore.setState({ settings: { ...useStore.getState().settings, onboarded: true, reduceMotion: true, dynamicIsland: true, homeWidgets: false, updates: { autoCheck: false } },
      chats: [{ id: 'search-test', title: 'Find this reference', kind: 'research', messages: [], updatedAt: Date.now(), createdAt: Date.now(), settings: {} }] })
    useUI.setState({ settingsTab: 'appearance', sidebarCollapsed: false, island: { kind: 'focus', remaining: 123, total: 1500 } })
    useBots.getState().create({ name: 'Research bot', job: 'Find sources' })
    useBots.getState().create({ name: 'Review bot', job: 'Review sources' })
    useBots.getState().setSettings({ paused: true })
  })
  const skip = page.getByRole('button', { name: 'Skip', exact: true })
  if (await skip.isVisible()) await skip.click()
  const palette = page.getByRole('region', { name: 'Palette workshop' })
  await palette.waitFor()
  await palette.getByRole('radio', { name: '5 colours' }).click()
  assert.equal(await palette.locator('input[type=color]').count(), 5)
  await palette.getByRole('button', { name: 'Generate a new palette' }).click()
  await palette.getByRole('textbox', { name: 'Palette theme name' }).fill('Browser test palette')
  const download = page.waitForEvent('download')
  await palette.getByRole('button', { name: 'Export theme CSS', exact: true }).click()
  assert.equal((await download).suggestedFilename(), 'research-palette.css')
  await palette.getByRole('button', { name: 'Apply palette theme' }).click()
  const applied = await page.evaluate(async () => {
    const { useStore } = await import('/src/stores/useStore.ts')
    return useStore.getState().settings.customPaletteTheme
  })
  assert.equal(applied.name, 'Browser test palette')
  assert.equal(applied.colours.length, 5)
  await page.waitForTimeout(600)
  await page.reload()
  await page.evaluate(async () => (await import('/src/stores/useUI.ts')).useUI.setState({ settingsTab: 'appearance' }))
  await palette.waitFor()
  await palette.getByRole('switch', { name: 'Use palette theme: Browser test palette' }).waitFor()
  await palette.getByText('Use palette theme: Browser test palette', { exact: true }).click()
  assert.equal(await page.evaluate(() => document.documentElement.style.getPropertyValue('--surface')), '')
  await palette.scrollIntoViewIfNeeded()
  await page.screenshot({ path: '.cache/bencho-review-results/palette.png' })

  await page.evaluate(async () => (await import('/src/stores/useUI.ts')).useUI.setState({ island: { kind: 'focus', remaining: 123, total: 1500 } }))
  await page.getByRole('button', { name: 'Expand activity island' }).click()
  await page.getByText('Focus session', { exact: true }).waitFor()
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('button', { name: 'Expand activity island' }).getAttribute('aria-expanded'), 'false')
  await page.goto(`${base}/#/chats`)
  await page.getByRole('button', { name: 'Search chats', exact: true }).click()
  const search = page.getByRole('textbox', { name: 'Search chats', exact: true })
  await search.fill('not in history')
  await page.getByText('No chats found.', { exact: true }).waitFor()
  await search.press('Escape')
  await page.getByRole('button', { name: /^Find this reference Research/ }).waitFor()

  await page.goto(`${base}/#/bots`)
  await page.getByRole('tab', { name: 'Group chats', exact: true }).click()
  await page.getByRole('button', { name: 'New', exact: true }).click()
  await page.getByRole('textbox', { name: 'Group name' }).fill('Source team')
  await page.getByRole('button', { name: 'Choose group bots' }).click()
  await page.getByRole('option', { name: /Research bot/ }).click()
  await page.getByRole('option', { name: /Review bot/ }).click()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Create group', exact: true }).click()
  assert.equal(await page.evaluate(async () => (await import('/src/lib/bots/store.ts')).useBots.getState().rooms[0].memberIds.length), 2)
  await page.getByRole('tab', { name: 'Bots', exact: true }).click()
  await page.getByRole('button', { name: /Routines \(0\)/ }).click()
  await page.getByRole('textbox', { name: 'Routine title' }).fill('Timed brief')
  await page.getByRole('textbox', { name: 'Routine instructions' }).fill('Summarize saved sources')
  await page.getByText('Choose the first run time', { exact: true }).click()
  const ruler = page.getByRole('slider', { name: 'Time', exact: true })
  await ruler.focus()
  await page.keyboard.press('ArrowRight')
  await page.waitForTimeout(150)
  assert.equal(await ruler.getAttribute('aria-valuenow'), '555')
  await page.getByRole('button', { name: 'Add routine', exact: true }).click()
  const routine = await page.evaluate(async () => (await import('/src/lib/bots/store.ts')).useBots.getState().bots[0].routines[0])
  assert.equal(new Date(routine.nextRunAt).getHours(), 9)
  assert.equal(new Date(routine.nextRunAt).getMinutes(), 15)
  await page.screenshot({ path: '.cache/bencho-review-results/bots.png' })

  await page.goto(`${base}/#/workflows`)
  await page.getByRole('button', { name: 'Create', exact: true }).click()
  await page.getByRole('button', { name: 'Blank workflow', exact: true }).click()
  await page.waitForURL(/#\/workflows\/.+/)
  await page.goto(`${base}/#/workflows`)
  await page.getByRole('button', { name: 'Automation actions', exact: true }).focus()
  const exp = page.waitForEvent('download')
  await page.getByRole('button', { name: /^Export / }).click()
  await exp
  await page.getByRole('button', { name: /^Delete / }).click()
  await page.getByRole('button', { name: 'Slide to confirm' }).focus()
  await page.keyboard.press('Enter')
  await page.getByText('No workflows yet.', { exact: false }).waitFor()
  assert.equal(await page.evaluate(async () => (await import('/src/stores/useStore.ts')).useStore.getState().workflows.length), 0)

  await page.evaluate(async () => (await import('/src/stores/useUI.ts')).useUI.setState({ settingsTab: 'profile' }))
  await page.goto(`${base}/#/settings`)
  const signature = page.getByRole('region', { name: 'Profile signature', exact: true })
  await signature.waitFor()
  const pad = await signature.locator('.sig').boundingBox()
  assert.ok(pad)
  await page.mouse.move(pad.x + 50, pad.y + 60)
  await page.mouse.down()
  await page.mouse.move(pad.x + 100, pad.y + 85, { steps: 10 })
  await page.mouse.move(pad.x + 150, pad.y + 50, { steps: 10 })
  await page.mouse.up()
  await signature.getByRole('button', { name: 'Save signature', exact: true }).click()
  await signature.getByRole('img', { name: 'Your saved profile signature' }).waitFor()
  await page.screenshot({ path: '.cache/bencho-review-results/signature.png' })
  await page.evaluate(async () => {
    const { useUI } = await import('/src/stores/useUI.ts')
    const { useStore } = await import('/src/stores/useStore.ts')
    useUI.setState({ settingsTab: 'usage' })
    const d = new Date(); const day = `${d.getFullYear()}-${String(d.getMonth()+1).padStart(2,'0')}-${String(d.getDate()).padStart(2,'0')}`
    useStore.setState({ usageByDay: { [day]: 1234 } })
  })
  await page.getByRole('region', { name: 'Recent token usage' }).waitFor()
  await page.getByText('1,234', { exact: true }).first().waitFor()
  await page.screenshot({ path: '.cache/bencho-review-results/usage.png' })
  assert.deepEqual(errors, [])
  console.log('PASS: palette roll/count/export/persist/restore, live island/Escape, search, real group creation, scrubbed routine time, workflow create/export/confirm, signature save, real usage; no page errors')
} finally { await browser.close() }
