import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium } from './node_modules/playwright-core/index.mjs'
const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE, chromiumSandbox: true, headless: true })
const base = process.env.SHELL_PREVIEW_URL ?? 'http://127.0.0.1:5173'
await mkdir('.cache/native-studio-results', { recursive: true })
try {
 const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
 const errors = []; page.on('pageerror', e => errors.push(e.message))
 await page.addInitScript(() => localStorage.setItem('re.data.main:research-engine-v1', JSON.stringify({ state: { settings: { onboarded: true, typeface: 'allo', compact: true, reduceMotion: true, experimentalTabBar: true, updates: { autoCheck: false }, theme: 'dark', workspaceLayout: 'focused' } }, version: 0 })))
 await page.route('**/api/**', route => route.fulfill({ json: {} }))
 await page.goto(`${base}/#/chats`)
 await page.getByRole('button', { name: 'Settings', exact: true }).waitFor()
 await page.waitForFunction(() => document.documentElement.dataset.typeface === 'allo')
 assert.ok(await page.evaluate(async () => { const fonts = await document.fonts.load('400 14px Allo'); return fonts.length > 0 }))
 assert.equal(await page.locator('button button').count(), 0, 'No nested notification trigger')
 assert.equal(await page.getByTestId('floating-navigation').locator('.lg-tab-bar').count(), 1, 'Actual Glisse bar, not a placeholder')
 await page.screenshot({ path: '.cache/native-studio-results/shell.png' })
 await page.getByRole('button', { name: 'Settings', exact: true }).click()
 const dialog = page.getByRole('dialog', { name: 'Settings', exact: true })
 await dialog.getByRole('button', { name: 'Appearance', exact: true }).click()
 const density = page.getByRole('radiogroup', { name: 'Layout density' })
 await density.scrollIntoViewIfNeeded()
 await density.getByRole('radio', { name: 'Compact', exact: true }).focus()
 await page.keyboard.press('ArrowLeft')
 assert.equal(await density.getByRole('radio', { name: 'Comfortable', exact: true }).isChecked(), true)
 await page.keyboard.press('ArrowRight')
 assert.equal(await density.getByRole('radio', { name: 'Compact', exact: true }).isChecked(), true)
 const switchControl = page.getByRole('switch', { name: 'Reduce motion', exact: true })
 await switchControl.scrollIntoViewIfNeeded()
 assert.ok(await switchControl.evaluate(el => el.getBoundingClientRect().width <= 40), 'Compact switch geometry')
 await switchControl.focus(); await page.keyboard.press('Space'); assert.equal(await switchControl.isChecked(), false)
 await page.keyboard.press('Space'); assert.equal(await switchControl.isChecked(), true)
 await page.screenshot({ path: '.cache/native-studio-results/settings.png' })
 // Selecting an existing typeface must still work (no migration over saved choices).
 const family = page.getByRole('combobox', { name: 'Font family', exact: true })
 await family.click(); await page.getByRole('option', { name: 'Inter', exact: true }).click()
 await page.waitForFunction(() => document.documentElement.dataset.typeface === 'inter')
 await family.click(); await page.getByRole('option', { name: 'Allo', exact: true }).click()
 await page.waitForFunction(() => document.documentElement.dataset.typeface === 'allo')
 await page.setViewportSize({ width: 390, height: 844 })
 await page.screenshot({ path: '.cache/native-studio-results/settings-narrow.png' })
 assert.ok(await dialog.evaluate(el => el.getBoundingClientRect().right <= innerWidth))
 await page.setViewportSize({ width: 1440, height: 1000 })
 await page.evaluate(() => document.body.style.zoom = '2')
 assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
 await page.evaluate(() => document.body.style.zoom = '')
 await dialog.getByRole('button', { name: 'Close settings', exact: true }).click()
 // Isolate static default reading background, without modifying optional selected effects.
 await page.evaluate(async () => { const { useStore } = await import('/src/stores/useStore.ts'); const id = useStore.getState().newChat(); location.hash = `/chat/${id}` })
 await page.getByRole('button', { name: 'Attach image', exact: true }).waitFor()
 assert.equal(await page.getByTestId('floating-navigation').count(), 0)
 const patterns = await page.evaluate(() => performance.getEntriesByType('resource').filter(e => /PatternWaves/.test(e.name)).map(e => e.name))
 assert.deepEqual(patterns, [], 'No unconditional PatternWaves module loaded')
 await page.screenshot({ path: '.cache/native-studio-results/chat.png' })
 assert.deepEqual(errors, [])
 console.log('PASS: local Allo, actual Glisse, no nested buttons, radio arrow keys, compact switch/Space, existing font selection, narrow and zoom overflow, active-chat clearance/static background; no page errors')
} finally { await browser.close() }
