#!/usr/bin/env node
// Token generators: tokens.json -> tokens.css (WebView/Tailwind), ReTheme.swift,
// ReTheme.kt. Deterministic output (no timestamps) so CI can diff.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const loadTokens = () => JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'))

/* ---------------- colour parsing ---------------- */

export function parseColor(c) {
  let m = /^#([0-9a-fA-F]{6})$/.exec(c)
  if (m) return { r: parseInt(m[1].slice(0, 2), 16), g: parseInt(m[1].slice(2, 4), 16), b: parseInt(m[1].slice(4, 6), 16), a: 1 }
  m = /^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/.exec(c)
  if (m) return { r: +m[1], g: +m[2], b: +m[3], a: parseFloat(m[4]) }
  throw new Error(`Unsupported colour in tokens.json: ${c}`)
}

const hex2 = (n) => Math.round(n * 255).toString(16).padStart(2, '0').toUpperCase()
const camel = (k) => k.replace(/^--/, '').replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())
const nsKey = (id) => id.replace(/-/g, '_').toUpperCase()

/* ---------------- CSS ---------------- */

export function toCss(t) {
  const L = ['/* Generated by packages/tokens/generate.mjs from tokens.json. Do not edit. */', ':root {']
  for (const [k, v] of Object.entries(t.radius)) L.push(`  --radius-${k}: ${v}px;`)
  for (let i = 1; i <= 10; i++) L.push(`  --space-${i}: ${i * t.space.base}px;`)
  L.push(`  --gutter-phone: ${t.space.gutter.phone}px;`)
  L.push(`  --gutter-large-phone: ${t.space.gutter.largePhone}px;`)
  L.push(`  --gutter-tablet: ${t.space.gutter.tablet}px;`)
  L.push(`  --target-min: ${t.target.ios}px;`)
  for (const [k, v] of Object.entries(t.type.roles)) L.push(`  --type-${k}: ${v.pt}px/${v.lineHeight}px;`)
  L.push(`  --font-ui: ${t.fonts.ui};`)
  L.push(`  --font-body: ${t.fonts.body};`)
  L.push(`  --font-mono: ${t.fonts.mono};`)
  L.push(`  --font-serif: ${t.fonts.serif};`)
  L.push(`  --spring: ${t.motion.springCurve};`)
  L.push(`  --reveal-curve: ${t.motion.revealCurve};`)
  for (const [k, v] of Object.entries(t.motion.durations)) L.push(`  --dur-${k}: ${v}ms;`)
  L.push(`  --font-scale: ${t.globals.fontScale};`)
  for (const [k, v] of Object.entries(t.gradients)) L.push(`  --grad-${k}: ${v};`)
  L.push('}')
  for (const th of t.themes) {
    L.push(`:root[data-theme="${th.id}"] {`)
    for (const [k, v] of Object.entries(th.vars)) L.push(`  ${k}: ${v};`)
    if (th.radius) for (const [k, v] of Object.entries(th.radius)) L.push(`  --radius-${k}: ${v}px;`)
    if (th.gradients) for (const [k, v] of Object.entries(th.gradients)) L.push(`  --grad-${k}: ${v};`)
    L.push('}')
  }
  return L.join('\n') + '\n'
}

/* ---------------- Swift ---------------- */

const swiftCase = (id) => { const c = camel('x-' + id).slice(1); return c.charAt(0).toLowerCase() + c.slice(1) }
const fmt4 = (n) => (Math.round(n * 10000) / 10000).toFixed(4)

export function toSwift(t) {
  const L = ['// Generated by packages/tokens/generate.mjs from tokens.json. Do not edit.', 'import SwiftUI', '', 'public enum ReThemeKind { case dark, light }', '']
  const colorRoles = [...new Set(t.themes.flatMap((th) => Object.keys(th.vars).filter((k) => k !== 'color-scheme').map(camel)))]
  L.push('public enum ReColorRole: String, CaseIterable {')
  L.push('  ' + colorRoles.map((r) => `case ${r}`).join('\n  '))
  L.push('}', '')
  L.push('public enum ReTheme: String, CaseIterable, Sendable {')
  L.push(t.themes.map((th) => `  case ${swiftCase(th.id)}`).join('\n'))
  L.push('')
  L.push('  public var displayName: String {')
  L.push('    switch self {')
  for (const th of t.themes) L.push(`    case ${swiftCase(th.id)}: return ${JSON.stringify(th.name)}`)
  L.push('    }')
  L.push('  }')
  L.push('')
  L.push('  public var kind: ReThemeKind {')
  L.push('    switch self {')
  for (const th of t.themes) L.push(`    case ${swiftCase(th.id)}: return .${th.kind}`)
  L.push('    }')
  L.push('  }')
  L.push('')
  L.push('  public func color(_ role: ReColorRole) -> Color {')
  L.push('    switch (self, role) {')
  for (const th of t.themes) for (const [k, v] of Object.entries(th.vars)) {
    if (k === 'color-scheme') continue
    const c = parseColor(v)
    L.push(`    case (${swiftCase(th.id)}, .${camel(k)}): return Color(red: ${fmt4(c.r / 255)}, green: ${fmt4(c.g / 255)}, blue: ${fmt4(c.b / 255)}, opacity: ${fmt4(c.a)})`)
  }
  L.push('    }')
  L.push('  }')
  L.push('}', '')
  L.push('public enum ReRadius {')
  for (const [k, v] of Object.entries(t.radius)) L.push(`  public static let ${k}: CGFloat = ${v}`)
  L.push('}', '')
  L.push('public enum ReMotion {')
  for (const [k, v] of Object.entries(t.motion.durations)) L.push(`  public static let ${k}: TimeInterval = ${fmt4(v / 1000)}`)
  const curve = t.motion.springCurve.match(/[\d.]+/g).join(', ')
  L.push(`  public static let springCurveComponents: [Double] = [${curve}]`)
  L.push('}')
  return L.join('\n') + '\n'
}

/* ---------------- Kotlin ---------------- */

export function toKotlin(t) {
  const L = ['// Generated by packages/tokens/generate.mjs from tokens.json. Do not edit.', 'package dev.researchengine.tokens', '', 'import androidx.compose.ui.graphics.Color', '']
  L.push('enum class ReThemeId(val displayName: String, val dark: Boolean) {')
  for (const th of t.themes) L.push(`  ${nsKey(th.id)}("${th.name.replace(/"/g, '\\"')}", ${th.kind === 'dark'}),`)
  L.push('}', '')
  L.push('object ReColors {')
  for (const th of t.themes) {
    L.push(`  object ${nsKey(th.id)} {`)
    for (const [k, v] of Object.entries(th.vars)) {
      if (k === 'color-scheme') continue
      const c = parseColor(v)
      L.push(`    val ${camel(k)}: Color = Color(0x${hex2(c.a)}${hex2(c.r)}${hex2(c.g)}${hex2(c.b)}u.toInt()) // ${v}`)
    }
    L.push('  }')
  }
  L.push('}', '')
  L.push('object ReRadius {')
  for (const [k, v] of Object.entries(t.radius)) L.push(`  const val ${camel(k)}: Int = ${v}`)
  L.push('}', '')
  L.push('object ReMotion {')
  for (const [k, v] of Object.entries(t.motion.durations)) L.push(`  const val ${camel(k)}Ms: Int = ${v}`)
  L.push('}')
  return L.join('\n') + '\n'
}

/* ---------------- entry ---------------- */

export function generateAll(outDir) {
  const t = loadTokens()
  mkdirSync(outDir, { recursive: true })
  writeFileSync(join(outDir, 'tokens.css'), toCss(t))
  writeFileSync(join(outDir, 'ReTheme.swift'), toSwift(t))
  writeFileSync(join(outDir, 'ReTheme.kt'), toKotlin(t))
  writeFileSync(join(outDir, 'themes.json'), JSON.stringify(t.themes, null, 2) + '\n')
  // mobile imports the whole JSON through the dist alias too:
  writeFileSync(join(outDir, 'tokens.json'), readFileSync(join(here, 'tokens.json'), 'utf8'))
  return outDir
}

if (process.argv[1] && resolve(process.argv[1]).endsWith('generate.mjs')) {
  const out = generateAll(process.argv[2] || join(here, 'dist'))
  console.log(`[tokens] wrote tokens.css, ReTheme.swift, ReTheme.kt, themes.json to ${out}`)
}
